    // Valida el campo ID. Retorna el número, o null si hay un error (ya avisó al
    // usuario)
    private Integer leerId(String mensajeVacio) {
        String id = txtId.getText().trim();

        if (id.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, mensajeVacio);
            return null;
        }

        try {
            int numeroId = Integer.parseInt(id);

            if (numeroId <= 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "El ID debe ser un número positivo.");
                return null;
            }
            return numeroId;

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "El ID debe contener solo números.");
            return null;
        }
    }

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnRegistrarActionPerformed
        String nombre = txtNombre.getText().trim();
        String descripcion = txtDescripcionareadetexto.getText().trim();

        // Comprobar que los campos estén completos
        if (txtId.getText().trim().isEmpty() || nombre.isEmpty() || descripcion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Complete todos los campos antes de registrar.");
            return;
        }

        Integer numeroId = leerId("Complete todos los campos antes de registrar.");
        if (numeroId == null) {
            return;
        }

        try {
            dao.registrar(numeroId, nombre, descripcion);
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Especialidad registrada correctamente.");
            btnLimpiarActionPerformed(null);

        } catch (java.sql.SQLIntegrityConstraintViolationException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Ya existe una especialidad con ese ID o con ese nombre.");
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Error al registrar: " + e.getMessage());
        }
    }// GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnBuscarActionPerformed
        Integer numeroId = leerId("Ingrese el ID de la especialidad que desea buscar.");
        if (numeroId == null) {
            return;
        }

        try {
            String[] datos = dao.buscar(numeroId);

            if (datos == null) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "No existe una especialidad con ID " + numeroId + ".");
                return;
            }

            txtId.setText(datos[0]);
            txtNombre.setText(datos[1]);
            txtDescripcionareadetexto.setText(datos[2]);

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Error al buscar: " + e.getMessage());
        }
    }// GEN-LAST:event_btnBuscarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnEditarActionPerformed
        Integer numeroId = leerId("Ingrese el ID de la especialidad que desea editar.");
        if (numeroId == null) {
            return;
        }

        String nombre = txtNombre.getText().trim();
        String descripcion = txtDescripcionareadetexto.getText().trim();

        if (nombre.isEmpty() || descripcion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Complete el nombre y la descripción antes de editar.");
            return;
        }

        try {
            if (dao.editar(numeroId, nombre, descripcion)) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Especialidad actualizada correctamente.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "No existe una especialidad con ID " + numeroId + ".");
            }

        } catch (java.sql.SQLIntegrityConstraintViolationException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Ya existe otra especialidad con ese nombre.");
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Error al editar: " + e.getMessage());
        }
    }// GEN-LAST:event_btnEditarActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnLimpiarActionPerformed
        txtId.setText("");
        txtNombre.setText("");
        txtDescripcionareadetexto.setText("");
    }// GEN-LAST:event_btnLimpiarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnEliminarActionPerformed
        Integer numeroId = leerId("Ingrese el ID de la especialidad que desea eliminar.");
        if (numeroId == null) {
            return;
        }

        int respuesta = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar la especialidad con ID " + numeroId + "?",
                "Confirmar eliminación",
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (respuesta != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (dao.eliminar(numeroId)) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Especialidad eliminada correctamente.");
                btnLimpiarActionPerformed(null);
            } else {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "No existe una especialidad con ID " + numeroId + ".");
            }

        } catch (java.sql.SQLIntegrityConstraintViolationException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "No se puede eliminar: hay profesionales u otros registros que usan esta especialidad.");
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Error al eliminar: " + e.getMessage());
        }
    }// GEN-LAST:event_btnEliminarActionPerformed

