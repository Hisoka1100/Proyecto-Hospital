    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButton3ActionPerformed
        Integer id = leerId();
        if (id == null)
            return;

        try {
            String[] datos = new ProfesionalDAO().buscar(id);

            if (datos == null) {
                mensaje("No existe un profesional con ese ID.");
                return;
            }
            jTextField8.setText(datos[1]);
            jComboBox2.setSelectedItem(datos[2]);
            jComboBox1.setSelectedItem(datos[3]);

        } catch (java.sql.SQLException e) {
            mensaje("Error al buscar: " + e.getMessage());
        }
    }// GEN-LAST:event_jButton3ActionPerformed

    // ---------- Métodos de apoyo ----------

    private void limpiar() {
        jTextField7.setText("");
        jTextField8.setText("");
        jComboBox1.setSelectedIndex(0);
        jComboBox2.setSelectedIndex(0);
        jTextField7.requestFocus();
    }

    private void mensaje(String texto) {
        javax.swing.JOptionPane.showMessageDialog(this, texto);
    }

    private Integer leerId() {
        String id = jTextField7.getText().trim();

        if (id.isEmpty()) {
            mensaje("Ingrese el ID del profesional.");
            return null;
        }
        try {
            int numero = Integer.parseInt(id);
            if (numero <= 0) {
                mensaje("El ID debe ser un número positivo.");
                return null;
            }
            return numero;
        } catch (NumberFormatException e) {
            mensaje("El ID debe contener solo números.");
            return null;
        }
    }

    private boolean camposCompletos() {
        if (jTextField8.getText().trim().isEmpty()
                || jComboBox1.getSelectedIndex() <= 0
                || jComboBox2.getSelectedIndex() <= 0) {
            mensaje("Complete todos los campos.");
            return false;
        }
        return true;
    }

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {
        Integer id = leerId();
        if (id == null || !camposCompletos())
            return;

        try {
            new ProfesionalDAO().registrar(id,
                    jTextField8.getText().trim(),
                    jComboBox2.getSelectedItem().toString(),
                    jComboBox1.getSelectedItem().toString());

            mensaje("Profesional registrado correctamente.");
            limpiar();

        } catch (java.sql.SQLIntegrityConstraintViolationException e) {
            mensaje("No se pudo registrar. El ID ya existe o falta un dato obligatorio.\n"
                    + e.getMessage());
        } catch (java.sql.SQLException e) {
            mensaje("Error al guardar: " + e.getMessage());
        }
    }

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {
        limpiar();
    }

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {
        Integer id = leerId();
        if (id == null || !camposCompletos())
            return;

        try {
            boolean ok = new ProfesionalDAO().editar(id,
                    jTextField8.getText().trim(),
                    jComboBox2.getSelectedItem().toString(),
                    jComboBox1.getSelectedItem().toString());

            mensaje(ok ? "Profesional actualizado." : "No existe un profesional con ese ID.");

        } catch (java.sql.SQLException e) {
            mensaje("Error al editar: " + e.getMessage());
        }
    }

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {
        Integer id = leerId();
        if (id == null)
            return;

        int respuesta = javax.swing.JOptionPane.showConfirmDialog(this,
                "¿Está seguro de eliminar al profesional con ID " + id + "?",
                "Confirmar eliminación",
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (respuesta != javax.swing.JOptionPane.YES_OPTION)
            return;

        try {
            boolean ok = new ProfesionalDAO().eliminar(id);
            mensaje(ok ? "Profesional eliminado." : "No existe un profesional con ese ID.");
            if (ok)
                limpiar();

        } catch (java.sql.SQLIntegrityConstraintViolationException e) {
            mensaje("No se puede eliminar: el profesional tiene consultas asociadas.");
        } catch (java.sql.SQLException e) {
            mensaje("Error al eliminar: " + e.getMessage());
        }
    }

