    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        


    String id = txtId.getText().trim();

    // Validar que se ingrese un ID
    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Ingresa el ID del paciente que deseas eliminar.");
        return;
    }

    // Validar que el ID sea numérico
    int numeroId;

    try {
        numeroId = Integer.parseInt(id);

        if (numeroId <= 0) {
            JOptionPane.showMessageDialog(this,
                    "El ID debe ser un número positivo.");
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "El ID debe contener solamente números.");
        return;
    }

    // Solicitar confirmación antes de eliminar
    int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "¿Estás seguro de eliminar este paciente?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
    );

    if (confirmacion != JOptionPane.YES_OPTION) {
        return;
    }

    // Eliminar paciente de MySQL
    try {
        PacienteDA0 dao = new PacienteDA0();

        boolean eliminado = dao.eliminar(numeroId);

        if (eliminado) {

            JOptionPane.showMessageDialog(this,
                    "Paciente eliminado correctamente.");
            cargarPacientes();

            // Limpiar formulario
            btnLimpiarActionPerformed(evt);

        } else {

            JOptionPane.showMessageDialog(this,
                    "No se encontró ningún paciente con ese ID.");
        }

    } catch (java.sql.SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error al eliminar el paciente: " + e.getMessage());
    }


    }//GEN-LAST:event_btnEliminarActionPerformed
     private boolean validarRut(String rut) {

    String cuerpo = rut.substring(0, rut.length() - 1);
    char dv = rut.charAt(rut.length() - 1);

    int suma = 0;
    int multiplicador = 2;

    for (int i = cuerpo.length() - 1; i >= 0; i--) {
        suma += (cuerpo.charAt(i) - '0') * multiplicador;
        multiplicador++;

        if (multiplicador > 7) {
            multiplicador = 2;
        }
    }

    int resultado = 11 - (suma % 11);

    char esperado;

    if (resultado == 11) {
        esperado = '0';
    } else if (resultado == 10) {
        esperado = 'K';
    } else {
        esperado = (char) ('0' + resultado);
    }

    return dv == esperado;
}    
     
private void cargarPacientes() {

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tablaPacientes.getModel();

    modelo.setRowCount(0);

    try {

        PacienteDA0 dao = new PacienteDA0();

        java.util.List<String[]> pacientes = dao.listar();

        for (String[] paciente : pacientes) {
            modelo.addRow(paciente);
        }

    } catch (java.sql.SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error al cargar pacientes: " + e.getMessage());
    }
}

